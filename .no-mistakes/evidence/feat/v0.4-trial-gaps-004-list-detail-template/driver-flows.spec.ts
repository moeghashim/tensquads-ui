 const download=await downloadPromise; await download.saveAs(evidence+'/filtered-orders.csv');
 expect(await readFile(evidence+'/filtered-orders.csv','utf8')).toBe('"Order","Customer","Date","Status"\r\n"1044","Yousef Nasser","2026-11-23","paid"');
 await page.getByRole('button',{name:'Status: All',exact:true}).click();
 await page.getByRole('menuitemradio',{name:'Failed',exact:true}).click();
