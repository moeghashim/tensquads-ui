import { expect, test } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const evidence = '~/.no-mistakes/evidence/01M7T96F3830VNXDNHBGZKXXNX';
for (const locale of ['en', 'ar'] as const) for (const theme of ['light','dark'] as const) {
 test(`fixture contents, focus, alignment, and internal scroll ${locale} ${theme}`, async ({page})=>{
  const observations: unknown[]=[];
  const ar=locale==='ar';
  await page.goto(`/components/DataTable?locale=${locale}&dir=${ar?'rtl':'ltr'}&theme=${theme}`);
  const table=page.locator('.dashboard-component-preview > [data-slot=card]').getByRole('table');
  await expect(table).toHaveAccessibleName(ar?'الشركات':'Companies');
  const fixture=page.getByRole('region',{name:ar?'عينة OpenUI':'OpenUI fixture'});
  await expect(fixture.getByRole('table')).toHaveAccessibleName(ar?'الشركات':'Companies');
  await expect(fixture.getByRole('cell',{name:ar?'أكمي':'Acme',exact:true})).toBeVisible();
  await expect(fixture.getByRole('cell',{name:ar?'١٤٩ دولاراً / شهرياً':'$149 / mo',exact:true})).toBeVisible();
  await expect(fixture.locator('tbody tr')).not.toHaveAttribute('tabindex');
  const row=table.getByRole('row',{name:/Northstar/});
  await row.focus();
  await page.keyboard.press('Tab');
  await page.keyboard.press('Shift+Tab');
  await expect(row).toBeFocused();
  const ring=await row.evaluate(e=>{const s=getComputedStyle(e);return {width:s.outlineWidth,offset:s.outlineOffset,color:s.outlineColor}});
  expect(ring).toEqual({width:'2px',offset:'2px',color:theme==='light'?'rgb(1, 105, 204)':'rgb(2, 133, 255)'});
  await expect(table.locator('td.is-end').first()).toHaveCSS('text-align','end');
  await expect(table.locator('td.is-end').first()).toHaveCSS('font-variant-numeric','tabular-nums');
  await page.screenshot({path:`${evidence}/focus-${locale}-${theme}.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  const scroll=table.locator('..');
  const dimensions=await scroll.evaluate(e=>({viewport:document.documentElement.clientWidth,page:document.documentElement.scrollWidth,client:e.clientWidth,content:e.scrollWidth}));
  expect(dimensions.page).toBeLessThanOrEqual(390);
  expect(dimensions.content).toBeGreaterThan(dimensions.client);
  await scroll.evaluate((e,rtl)=>{e.scrollLeft=rtl?-e.scrollWidth:e.scrollWidth},ar);
  await expect(table.getByRole('columnheader',{name:ar?'الحالة':'Status'})).toBeInViewport();
  await page.screenshot({path:`${evidence}/scrolled-${locale}-${theme}-390.png`,fullPage:true});
  observations.push({locale,theme,ring,dimensions,scrollLeft:await scroll.evaluate(e=>e.scrollLeft),fixture:await fixture.innerText()});
  await page.goto(`/components/EmptyState?locale=${locale}&dir=${ar?'rtl':'ltr'}&theme=${theme}`);
  const emptyFixture=page.getByRole('region',{name:ar?'عينة OpenUI':'OpenUI fixture'});
  await expect(emptyFixture.getByRole('heading',{name:ar?'لا توجد شركات بعد':'No companies yet'})).toBeVisible();
  await expect(emptyFixture.getByText(ar?'أضف شركة لتظهر في هذه القائمة.':'Add a company to see it listed here.')).toBeVisible();
  observations.push({emptyFixture:await emptyFixture.innerText()});
  await writeFile(`${evidence}/observations-${locale}-${theme}.json`,JSON.stringify(observations,null,2));
 });
}
for(const dir of ['ltr','rtl']) test(`native nested controls retain Space and Enter behavior ${dir}`,async({page})=>{
 await page.goto('http://127.0.0.1:5174/.review/live-surface/index.html');
 await page.locator('html').evaluate((e,d)=>e.dir=d,dir);
 const status=page.getByRole('status');
 const input=page.getByRole('textbox',{name:'Company note'});
 await input.focus();
 await page.keyboard.type('alpha beta');
 await page.keyboard.press('Enter');
 await expect(input).toHaveValue('alpha beta');
 await expect(status).toHaveText('Selected: other; selection calls: 0; opened: 0');
 const button=page.getByRole('button',{name:'Open company'});
 await button.focus();
 await page.keyboard.press('Space');
 await expect(status).toHaveText('Selected: controls; selection calls: 1; opened: 1');
 await page.keyboard.press('Enter');
 await expect(status).toHaveText('Selected: controls; selection calls: 2; opened: 2');
 const other=page.getByRole('row',{name:'Other company'});
 await other.focus(); await page.keyboard.press('Space');
 await expect(other).toHaveAttribute('aria-selected','true');
 await expect(status).toHaveText('Selected: other; selection calls: 3; opened: 2');
 const secondary=page.getByText('A long billing description with a complete ending visible in its title');
 await expect(secondary).toHaveAttribute('title','A long billing description with a complete ending visible in its title');
 expect(await secondary.evaluate(e=>e.scrollWidth>e.clientWidth)).toBe(true);
 await page.screenshot({path:`${evidence}/nested-controls-${dir}.png`,fullPage:true});
 await writeFile(`${evidence}/nested-controls-${dir}.json`,JSON.stringify({status:await status.innerText(),note:await input.inputValue(),title:await secondary.getAttribute('title')},null,2));
});
