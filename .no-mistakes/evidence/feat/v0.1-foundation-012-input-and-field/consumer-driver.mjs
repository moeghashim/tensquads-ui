import {createServer} from 'vite';
import {chromium} from 'playwright';
import {expect} from '@playwright/test';
import {writeFile,mkdir} from 'node:fs/promises';
const evidence='~/.no-mistakes/evidence/01M7PW8P4S5GKXNZ25E44Z2QJ6';
await mkdir(evidence,{recursive:true});
const server=await createServer({configFile:false,root:process.cwd()+'/.phase-test',resolve:{dedupe:['react','react-dom']},server:{port:5184,strictPort:true,fs:{allow:[process.cwd()]}},oxc:{jsx:{runtime:'automatic'}}});
let browser; const records=[];
try {
 await server.listen(); browser=await chromium.launch();
 const page=await browser.newPage();
 page.on('pageerror',e=>records.push({pageError:e.message}));
 for(const [locale,dir,theme] of [['en','ltr','light'],['ar','rtl','dark']]) {
  await page.goto(`http://localhost:5184/?locale=${locale}`);
  await page.evaluate(({locale,dir,theme})=>{document.documentElement.lang=locale;document.documentElement.dir=dir;document.documentElement.dataset.theme=theme},{locale,dir,theme});
  const input=page.getByRole('textbox',{name:'Stream input',exact:true});
  const field=page.getByRole('textbox',{name:'Stream field',exact:true});
  await expect(input).toHaveValue('N'); await expect(field).toHaveValue('N');
  await input.evaluate(el=>el.dataset.mounted='original'); await field.evaluate(el=>el.dataset.mounted='original');
  await page.getByRole('button',{name:'Complete streams'}).click();
  for(const el of [input,field]) {await expect(el).toHaveValue('Northstar');await expect(el).toHaveAttribute('data-mounted','original');await el.fill(locale==='ar'?'مشروعي':'My project');}
  await page.getByRole('button',{name:/Unrelated update/}).click();
  for(const el of [input,field]) await expect(el).toHaveValue(locale==='ar'?'مشروعي':'My project');
  await page.screenshot({path:`${evidence}/stream-complete-${locale}.png`,fullPage:true});
  await page.getByRole('button',{name:'Empty streams'}).click();
  for(const el of [input,field]) await expect(el).toHaveValue('');
  records.push({scenario:'Incremental OpenUI',locale,result:'pass',observed:'N → Northstar in same mounted controls; edits survive unrelated rerender; new empty value clears both'});
  const site=page.getByRole('textbox',{name:'Website',exact:true});
  const group=page.getByTestId('input-group');
  await expect(group).toHaveJSProperty('tagName','SECTION'); await expect(group).toHaveClass('filled');
  await expect(group).toHaveAttribute('data-slot','input-group');
  await page.getByRole('button',{name:'Clear website'}).focus(); await page.keyboard.press('Enter');
  await expect(site).toHaveValue('');await expect(site).toBeFocused();
  await expect(page.getByRole('button',{name:'Clear website'})).toHaveCount(0);
  await expect(page.getByLabel('Value event')).toContainText('clear-press');
  await site.pressSequentially('new.example');await expect(page.getByRole('button',{name:'Clear website'})).toBeVisible();
  const controlled=page.getByRole('searchbox',{name:'Controlled search'});
  await controlled.fill('query');await expect(controlled).toHaveValue('query');
  await expect(page.getByLabel('Value event')).toContainText('input-change');
  await controlled.fill('123456789012345');await expect(controlled).toHaveValue('123456789012');
  records.push({scenario:'Input composition and controlled native props',locale,result:'pass',observed:'InputGroup renders section and filled state; keyboard clear focuses input with clear-press event; custom search input updates controlled value and enforces maxlength'});
  const set=page.getByRole('group',{name:'Address'});
  await expect(set).toHaveAccessibleDescription('Delivery address');await expect(set).toHaveAttribute('data-slot','field-set');
  await expect(page.getByText('Address',{exact:true})).toHaveJSProperty('tagName','DIV');
  await expect(page.getByTestId('field-group')).toHaveJSProperty('tagName','SECTION');
  const city=page.getByRole('textbox',{name:'City',exact:true}),postal=page.getByRole('textbox',{name:'Postal code'});
  await expect(city).toBeDisabled();await expect(postal).toBeDisabled();
  const email=page.getByRole('textbox',{name:'Email',exact:true});
  await page.getByRole('button',{name:'Submit',exact:true}).click();
  await expect(email).toBeFocused();await expect(email).toHaveAttribute('aria-invalid','true');
  await expect(email).toHaveAccessibleDescription('Account notices Enter an email address.');
  await email.fill('bad');await page.getByRole('button',{name:'Submit',exact:true}).click();
  await expect(page.getByText('Use a valid email address.',{exact:true})).toBeVisible();
  await email.fill('user@example.com');await page.getByRole('button',{name:'Submit',exact:true}).click();
  await expect(page.getByLabel('Submitted values')).toHaveText(JSON.stringify({email:'user@example.com',reference:'fixed'}));
  await page.getByRole('textbox',{name:'Read only',exact:true}).press('End');await page.keyboard.type('changed');
  await expect(page.getByRole('textbox',{name:'Read only',exact:true})).toHaveValue('fixed');
  await page.getByRole('button',{name:'Toggle address'}).click();
  await expect(city).toBeEnabled();await expect(postal).toBeEnabled();
  await page.getByText('City',{exact:true}).click();await expect(city).toBeFocused();
  await city.fill(locale==='ar'?'الرياض':'Austin');await postal.fill('78701');
  await page.getByRole('button',{name:'Submit',exact:true}).click();
  await expect(page.getByLabel('Submitted values')).toHaveText(JSON.stringify({city:locale==='ar'?'الرياض':'Austin',postal:'78701',email:'user@example.com',reference:'fixed'}));
  await page.screenshot({path:`${evidence}/parts-and-form-${locale}.png`,fullPage:true});
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await expect(city).toHaveValue('Chicago');await expect(postal).toHaveValue('60601');await expect(email).toHaveValue('');
  await expect(page.getByText('Enter an email address.',{exact:true})).toBeHidden();
  records.push({scenario:'Field parts, validation and form semantics',locale,result:'pass',observed:'Legend and description name group; disabled fields excluded from FormData; enable restores editing; labels focus controls; required/email errors associate to input; readonly submitted unchanged; reset restores defaults and hides errors'});
 }
 if(records.some(r=>r.pageError)) throw Error('Browser errors');
} catch(error) {records.push({failure:error.stack});process.exitCode=1;} finally {await writeFile(`${evidence}/consumer-results.json`,JSON.stringify(records,null,2)); if(browser) await browser.close();await server.close();console.log(JSON.stringify(records,null,2));}
