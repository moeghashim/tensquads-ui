 await expect(page.locator('.stream-code__line')).toHaveCount(7);
 results.push({scenario:'Reduced-motion load and replay show complete fixture immediately'});
 await page.getByRole('radio',{name:'System',exact:true}).click();
 await expect(page).toHaveURL(/theme=system/);
 await expect(page.locator('html')).not.toHaveAttribute('data-theme');
 await page.emulateMedia({colorScheme:'dark'});
 const dark=await page.locator('html').evaluate(el=>getComputedStyle(el).backgroundColor);
 await page.emulateMedia({colorScheme:'light'});
 const light=await page.locator('html').evaluate(el=>getComputedStyle(el).backgroundColor);
 expect(dark).not.toBe(light);
 await page.getByRole('navigation').getByRole('link',{name:'Components',exact:true}).click();
 await expect(page).toHaveURL(/components\?locale=en&dir=ltr&theme=system/);
 await page.getByRole('navigation').getByRole('link',{name:'Get started',exact:true}).click();
 await expect(page.getByRole('heading',{level:1})).toHaveText('Get started');
