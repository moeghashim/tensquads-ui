 const clipboard=await page.evaluate(()=>navigator.clipboard.readText());
 expect(clipboard).toBe('npm install github:moeghashim/tensquads-ui#<commit-sha>');
 results.push({scenario:'Actual browser clipboard receives the pinned install command',clipboard});
 const pane=page.locator('.stream-screen');
 await expect(pane.getByRole('button',{name:'Approve plan',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Replay',exact:true}).click();
 await expect(page.locator('.stream-code__line')).toHaveCount(0);
 await expect(page.locator('.stream-code__line')).toHaveCount(7);
 await expect(pane.getByRole('button',{name:'Approve plan',exact:true})).toBeVisible();
 await pane.getByRole('textbox',{name:'Store name'}).fill('Disposable store');
 await expect(pane.getByRole('textbox',{name:'Store name'})).toHaveValue('Disposable store');
 const toggle=pane.getByRole('switch',{name:'Email me when done'});
 await expect(toggle).toHaveAttribute('aria-checked','true'); await toggle.click(); await expect(toggle).toHaveAttribute('aria-checked','false');
 await pane.getByRole('radio',{name:'Monthly',exact:true}).click();
 await expect(pane.getByRole('radio',{name:'Monthly',exact:true})).toBeChecked();
 await pane.getByRole('button',{name:'Send back',exact:true}).click();
 await pane.getByRole('button',{name:'Approve plan',exact:true}).click();
 await expect(page).toHaveURL('http://localhost:5173/?locale=en&dir=ltr&theme=light');
 await page.screenshot({path:`${evidence}/demo-interacted-en.png`,fullPage:true});
 expect(external).toEqual([]); results.push({scenario:'Replay advances from zero to seven fixture lines; rendered form controls work; demo actions retain local page',externalRequests:external});
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.reload();
 await expect(page.locator('.stream-code__line')).toHaveCount(7);
