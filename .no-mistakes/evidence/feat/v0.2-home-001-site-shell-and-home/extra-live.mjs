 results.push({scenario:'System theme follows OS and primary navigation retains settings',dark,light});
 expect(errors).toEqual([]);
 await writeFile(`${evidence}/extra-live-results.json`,JSON.stringify({results,errors},null,2));
 console.log(JSON.stringify(results,null,2));
