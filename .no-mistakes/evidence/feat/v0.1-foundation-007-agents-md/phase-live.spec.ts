import { expect, test } from '@playwright/test';
const evidence = '~/.no-mistakes/evidence/01M7P7TKPENMYBBZWNRJ2G8QNA';
test('user controls persist across navigation and reload; invalid input falls back', async ({page}) => {
 page.on('pageerror', error => console.log('PAGE ERROR',error.message));
 await page.goto('/');
 await page.waitForLoadState('networkidle');
 await expect(page.locator('html')).toHaveAttribute('lang', 'en');
 await page.getByRole('combobox', {name:'Locale',exact:true}).selectOption('ar');
 await expect(page.locator('html')).toHaveAttribute('dir','rtl');
 await page.getByRole('combobox', {name:'السمة',exact:true}).selectOption('dark');
 await page.getByRole('combobox', {name:'الاتجاه',exact:true}).selectOption('ltr');
 await expect(page.locator('html')).toHaveAttribute('dir','ltr');
 await page.reload();
 await expect(page.locator('html')).toHaveAttribute('lang','ar');
 await expect(page.locator('html')).toHaveAttribute('dir','ltr');
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.getByRole('combobox', {name:'اللغة',exact:true}).selectOption('en');
 await page.getByRole('combobox', {name:'Locale',exact:true}).selectOption('ar');
 await expect(page.locator('html')).toHaveAttribute('dir','rtl');
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>document.fonts.ready);
 await page.screenshot({path:`${evidence}/gallery-ar-rtl-dark-mobile.png`,fullPage:true});
 await page.getByRole('link',{name:'Example',exact:true}).click();
 await expect(page.getByText('تم عرض عينة OpenUI باللغة العربية',{exact:true})).toBeVisible();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.screenshot({path:`${evidence}/fixture-ar-rtl-dark.png`,fullPage:true});
 await page.getByRole('link',{name:'Back to gallery'}).click();
 await expect(page.getByRole('combobox', {name:'السمة',exact:true})).toHaveValue('dark');
 await page.goto('/?locale=invalid&dir=invalid&theme=invalid');
 await expect(page.locator('html')).toHaveAttribute('lang','en');
 await expect(page.locator('html')).toHaveAttribute('dir','ltr');
 await expect(page.locator('html')).not.toHaveAttribute('data-theme');
 await page.emulateMedia({colorScheme:'dark'});
 const dark = await page.locator('html').evaluate(e=>getComputedStyle(e).backgroundColor);
 await page.emulateMedia({colorScheme:'light'});
 const light = await page.locator('html').evaluate(e=>getComputedStyle(e).backgroundColor);
 expect(dark).not.toEqual(light);
 await page.setViewportSize({width:1440,height:900});
 await page.screenshot({path:`${evidence}/gallery-default-light-desktop.png`,fullPage:true});
 await page.goto('/components/NoSuchComponent?locale=ar&dir=rtl&theme=dark');
 await expect(page.getByText('No ar OpenUI fixture is registered for this component.',{exact:true})).toBeVisible();
 await page.screenshot({path:`${evidence}/missing-component-fallback.png`,fullPage:true});
 await page.goto('/components/Example?locale=en&dir=ltr&theme=light');
 await expect(page.getByText('OpenUI fixture rendered in English',{exact:true})).toBeVisible();
 await page.screenshot({path:`${evidence}/fixture-en-ltr-light.png`,fullPage:true});
});
