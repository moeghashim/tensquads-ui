import { chromium, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
const evidence='~/.no-mistakes/evidence/01M82S7VFJW5G7XTMW0RN9T8XN';
const browser=await chromium.launch();
const log=[];
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000},hasTouch:true});
 const page=await context.newPage();
 const cdp=await context.newCDPSession(page);
 await page.goto('http://localhost:5173/components/Palette?locale=en&dir=ltr&theme=light');
 await page.evaluate(()=>document.fonts.ready);
 const row=page.getByRole('toolbar',{name:'Workflow nodes'}).getByRole('button',{name:'Agent',exact:true});
 const nodes=page.locator('.palette-preview [data-node-id]');
 await row.scrollIntoViewIfNeeded();
 const center=async loc=>{const b=await loc.boundingBox();return {x:b.x+b.width/2,y:b.y+b.height/2};};
 let p=await center(row);
 await page.touchscreen.tap(p.x,p.y);
 await expect(nodes).toHaveCount(2);
 await expect(page.locator('.palette-preview')).toHaveAttribute('data-last-source','touch');
 log.push('Touch tap inserted exactly one Agent with source touch.');
 p=await center(row);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[p]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:p.x,y:p.y+120}]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 await expect(page.locator('.ts-palette__ghost')).toHaveCount(0);
 await expect(nodes).toHaveCount(2);
 log.push('Touch swipe created no drag ghost and inserted no node.');
 await row.scrollIntoViewIfNeeded();
 p=await center(row);
 const canvas=page.getByRole('region',{name:'Workflow builder'});
 const b=await canvas.boundingBox();
 const place={x:b.x+b.width*.7,y:b.y+b.height*.75};
 const pen=async(type,point,buttons)=>cdp.send('Input.dispatchMouseEvent',{type,...point,button:type==='mouseMoved'?'none':'left',buttons,pointerType:'pen',...(type==='mouseMoved'?{}:{clickCount:1})});
 await pen('mouseMoved',p,0); await pen('mousePressed',p,1);
 for(let i=1;i<=12;i++) await pen('mouseMoved',{x:p.x+(place.x-p.x)*i/12,y:p.y+(place.y-p.y)*i/12},1);
 await expect(page.locator('.ts-palette__ghost')).toBeVisible();
 await pen('mouseReleased',place,0);
 await expect(nodes).toHaveCount(3);
 await expect(page.locator('.palette-preview')).toHaveAttribute('data-last-source','pen');
 const inserted=await nodes.last().boundingBox();
 expect(Math.abs(inserted.x-place.x)).toBeLessThanOrEqual(2);
 expect(Math.abs(inserted.y-place.y)).toBeLessThanOrEqual(2);
 log.push(`Pen drag inserted one Agent at pointer (${place.x}, ${place.y}); rendered top-left (${inserted.x}, ${inserted.y}).`);
 await page.screenshot({path:evidence+'/touch-pen-palette.png',fullPage:true});
 // Actively reject a drop on another part of the palette overlay.
 p=await center(row); const overlay=await center(page.getByRole('toolbar',{name:'Workflow nodes'}).getByRole('button',{name:'Note',exact:true}));
 await page.mouse.move(p.x,p.y);await page.mouse.down();await page.mouse.move(overlay.x,overlay.y,{steps:12});
 await expect(page.locator('.ts-palette__ghost')).toBeVisible();await page.mouse.up();await expect(nodes).toHaveCount(3);
 log.push('Mouse drop onto Palette overlay inserted no node.');
 await row.focus();await page.keyboard.press('End');await expect(page.getByRole('toolbar',{name:'Workflow nodes'}).getByRole('button',{name:'Set state',exact:true})).toBeFocused();
 await page.keyboard.press('ArrowDown');await expect(page.getByRole('toolbar',{name:'Workflow nodes'}).getByRole('button',{name:'Set state',exact:true})).toBeFocused();
 await page.keyboard.press('Home');await expect(row).toBeFocused();await page.keyboard.press('ArrowUp');await expect(row).toBeFocused();
 log.push('Home/End reached first/last row; arrows did not wrap at boundaries.');
 // Disconnect a previously selected target entirely through the keyboard.
 await page.goto('http://localhost:5173/components/Inspector?locale=en&dir=ltr&theme=light');
 const connects=page.getByRole('combobox',{name:'Connects to'});
 await connects.focus();await page.keyboard.press('Enter');
 const list=page.getByRole('listbox');await expect(list.getByRole('option',{name:'Draft reply',exact:true})).toHaveAttribute('aria-selected','true');
 await page.keyboard.press('Enter');await expect(list.getByRole('option',{selected:true})).toHaveCount(0);
 await page.keyboard.press('Escape');await expect(connects).toBeFocused();
 await connects.press('Enter');await expect(list.getByRole('option',{selected:true})).toHaveCount(0);
 log.push('Keyboard deselected existing Draft reply connection; reopening retained no selected targets.');
 await page.screenshot({path:evidence+'/inspector-disconnected.png',fullPage:true});
 await context.close();
} finally { await browser.close(); await writeFile(evidence+'/supplemental-live.txt',log.join('\n')+'\n'); }
