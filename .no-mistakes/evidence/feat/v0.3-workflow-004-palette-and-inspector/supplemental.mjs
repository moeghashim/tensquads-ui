import { writeFile } from 'node:fs/promises';
const { chromium, expect } = await import(process.cwd() + '/node_modules/@playwright/test/index.mjs');
const out='~/.no-mistakes/evidence/01M82S7VFJW5G7XTMW0RN9T8XN';
const browser=await chromium.launch();
const results=[];
try {
 for (const locale of ['en','ar']) {
  const ar=locale==='ar';
  const context=await browser.newContext({viewport:{width:1440,height:1000},hasTouch:true});
  const page=await context.newPage();
  const open=async(name)=>{await page.goto(`http://localhost:5173/components/${name}?locale=${locale}&dir=${ar?'rtl':'ltr'}&theme=light`);await page.evaluate(()=>document.fonts.ready);};
  await open('Palette');
  const palette=page.locator('.ts-palette');
  const rows=palette.getByRole('button');
  await expect(rows).toHaveCount(12);
  await expect(palette.locator('.ts-palette__heading')).toHaveText(ar?['الأساسيات','الأدوات','المنطق','البيانات']:['Core','Tools','Logic','Data']);
  if (!ar) await expect(rows).toHaveText(['Agent','End','Note','File search','Guardrails','MCP','If/else','While','User approval','Classify','Transform','Set state']);
  await rows.first().focus();
  await page.keyboard.press('End'); await expect(rows.last()).toBeFocused();
  await page.keyboard.press('ArrowDown'); await expect(rows.last()).toBeFocused();
  await page.keyboard.press('Home'); await expect(rows.first()).toBeFocused();
  await page.keyboard.press('ArrowUp'); await expect(rows.first()).toBeFocused();
  expect(await rows.evaluateAll(es=>es.filter(e=>e.tabIndex===0).length)).toBe(1);
  results.push({name:`${locale}: default catalogue, single tab stop, Home/End and no wrapping`,result:'pass'});
  const canvas=page.locator('.palette-preview .ts-canvas');
  await canvas.scrollIntoViewIfNeeded();
  const row=rows.first();
  const rb=await row.boundingBox(), cb=await canvas.boundingBox();
  const start={x:rb.x+rb.width/2,y:rb.y+rb.height/2};
  const end={x:cb.x+cb.width*(ar?0.28:0.72),y:cb.y+cb.height*0.76};
  const nodes=canvas.locator('[data-node-id]');
  const cdp=await context.newCDPSession(page);
  await cdp.send('Input.dispatchMouseEvent',{type:'mouseMoved',...start,pointerType:'pen'});
  await cdp.send('Input.dispatchMouseEvent',{type:'mousePressed',...start,button:'left',buttons:1,clickCount:1,pointerType:'pen'});
  await cdp.send('Input.dispatchMouseEvent',{type:'mouseMoved',...end,button:'left',buttons:1,pointerType:'pen'});
  await expect(page.locator('.ts-palette__ghost')).toBeVisible();
  await page.screenshot({path:`${out}/pen-drag-${locale}.png`,fullPage:true});
  await cdp.send('Input.dispatchMouseEvent',{type:'mouseReleased',...end,button:'left',buttons:0,clickCount:1,pointerType:'pen'});
  await expect(nodes).toHaveCount(2);
  await expect(page.locator('.palette-preview')).toHaveAttribute('data-last-source','pen');
  const inserted=await nodes.last().boundingBox();
  expect(Math.abs((ar?inserted.x+inserted.width:inserted.x)-end.x)).toBeLessThan(2);
  expect(Math.abs(inserted.y-end.y)).toBeLessThan(2);
  results.push({name:`${locale}: browser pen drag inserts exactly one node at logical drop point`,result:'pass'});
  const drag=async(to)=>{await page.mouse.move(start.x,start.y);await page.mouse.down();await page.mouse.move(end.x,end.y,{steps:6});await expect(page.locator('.ts-palette__ghost')).toBeVisible();await page.mouse.move(to.x,to.y,{steps:6});await page.mouse.up();await expect(page.locator('.ts-palette__ghost')).toHaveCount(0);await expect(nodes).toHaveCount(2);};
  await drag({x:cb.x+cb.width/2,y:cb.y-12});
  await drag({x:start.x,y:start.y+45});
  results.push({name:`${locale}: outside and overlay drops never insert nodes`,result:'pass'});
  await row.tap();
  await expect(nodes).toHaveCount(3);
  await expect(page.locator('.palette-preview')).toHaveAttribute('data-last-source','touch');
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[start]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[end]});
  await expect(page.locator('.ts-palette__ghost')).toHaveCount(0);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await expect(nodes).toHaveCount(3);
  results.push({name:`${locale}: real browser touch tap inserts; touch swipe does not drag or insert`,result:'pass'});
  await open('Inspector');
  const inspector=page.locator('.ts-inspector');
  const name=inspector.getByRole('textbox',{name:ar?'الاسم':'Name',exact:true});
  await name.fill(ar?'وكيل تجريبي':'Edited agent');
  await name.press('Tab'); await expect(name).toHaveValue(ar?'وكيل تجريبي':'Edited agent');
  const connects=inspector.getByRole('combobox',{name:ar?'يتصل بـ':'Connects to'});
  await connects.focus();await page.keyboard.press('Enter');
  const list=page.getByRole('listbox');
  await expect(list.getByRole('option',{selected:true})).toHaveCount(1);
  await page.keyboard.press('Home');await page.keyboard.press('Enter');
  await expect(list.getByRole('option',{selected:true})).toHaveCount(0);
  await page.keyboard.press('Escape');await expect(connects).toBeFocused();
  await expect(connects).toContainText(ar?'لا شيء':'None');
  await page.keyboard.press('Enter');await page.keyboard.press('End');await page.keyboard.press('Enter');
  await expect(list.getByRole('option',{selected:true})).toHaveText(ar?'أرشفة':'Archive');
  await page.keyboard.press('Escape');await expect(connects).toContainText(ar?'أرشفة':'Archive');
  await expect(name).toHaveValue(ar?'وكيل تجريبي':'Edited agent');
  await page.screenshot({path:`${out}/inspector-keyboard-edited-${locale}.png`,fullPage:true});
  results.push({name:`${locale}: keyboard removes final connection and reconnects Archive without losing text edits`,result:'pass'});
  await context.close();
 }
} catch(error) {results.push({result:'fail',error:String(error),stack:error.stack});process.exitCode=1;} finally {await browser.close();await writeFile(`${out}/supplemental-results.json`,JSON.stringify(results,null,2));console.log(JSON.stringify(results,null,2));}
